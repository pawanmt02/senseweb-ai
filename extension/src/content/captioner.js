(function() {
  const MESSAGE_TYPES = {
    CAPTION_IMAGE: 'CAPTION_IMAGE'
  };

  let autoCaptionEnabled = false;
  let activeRequests = 0;
  const MAX_CONCURRENT_REQUESTS = 3;
  const queue = [];

  // Check initial profile
  chrome.storage.sync.get(['profiles'], (result) => {
    if (result.profiles && result.profiles.caption_images) {
      autoCaptionEnabled = true;
      processImages();
    }
  });

  chrome.runtime.onMessage.addListener((request) => {
    if (request.type === 'TOGGLE_PROFILE' && request.payload.profiles) {
      // Assuming caption_images might be a profile option, though not in the core list.
      // We will listen for it if needed, or caption is always active.
      autoCaptionEnabled = true; // Let's default to true for now unless specified
      processImages();
    }
  });

  function getNearbyText(img) {
    let context = '';
    let current = img.parentElement;
    while (current && current !== document.body && context.length < 100) {
      const text = current.innerText || current.textContent;
      if (text) {
        context = text.substring(0, 100).trim();
        break;
      }
      current = current.parentElement;
    }
    return context;
  }

  function processImages() {
    const images = Array.from(document.querySelectorAll('img[data-senseweb-needs-caption]:not([data-senseweb-captioning])'));
    images.forEach(img => {
      queue.push(img);
      img.setAttribute('data-senseweb-captioning', 'true');
    });
    processQueue();
  }

  function processQueue() {
    if (activeRequests >= MAX_CONCURRENT_REQUESTS || queue.length === 0) return;

    const img = queue.shift();
    activeRequests++;

    img.classList.add('senseweb-loading');

    const context = getNearbyText(img);
    
    chrome.runtime.sendMessage({
      type: MESSAGE_TYPES.CAPTION_IMAGE,
      payload: { image_url: img.src, context }
    }, (response) => {
      activeRequests--;
      img.classList.remove('senseweb-loading');
      
      if (chrome.runtime.lastError || !response || response.error) {
        // Backend offline — show subtle indicator, don't spam errors
        img.removeAttribute('data-senseweb-captioning');
        img.classList.add('senseweb-offline-skip');
        processQueue();
        return;
      }

      if (response.caption) {
        img.alt = response.caption;
        img.setAttribute('aria-label', response.caption);
        img.removeAttribute('data-senseweb-needs-caption');
        
        // Add badge
        const badge = document.createElement('div');
        badge.className = 'senseweb-caption-badge';
        badge.innerText = 'AI';
        badge.setAttribute('title', 'Alt-text generated by SenseWeb AI');
        badge.setAttribute('data-senseweb-container', 'true');
        
        const wrapper = document.createElement('div');
        wrapper.style.position = 'relative';
        wrapper.style.display = 'inline-block';
        wrapper.setAttribute('data-senseweb-container', 'true');
        
        if (img.parentNode) {
          img.parentNode.insertBefore(wrapper, img);
          wrapper.appendChild(img);
          wrapper.appendChild(badge);
        }
      }
      
      processQueue();
    });
  }

  document.addEventListener('senseweb:dom-updated', () => {
    if (autoCaptionEnabled) {
      processImages();
    }
  });

  // Enable by default for this test
  autoCaptionEnabled = true;

})();
